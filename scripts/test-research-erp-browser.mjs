import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
import { seoulDate } from "../js/research-erp-data.js";

if (!process.env.PLAYWRIGHT_MODULE) throw new Error("Set PLAYWRIGHT_MODULE to the local playwright module path.");
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE);
const base = process.env.ERP_TEST_ORIGIN || "http://127.0.0.1:8789";
const output = new URL("../output/playwright/", import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
const errors = []; page.on("pageerror", error => errors.push(error.message));
page.on("dialog", dialog => dialog.accept());
let rows = [], postIds = [], rejectSave = false, rejectLoad = false, loadReason = "temporarily_unavailable";
const date = seoulDate();
const entry = (id, category, amount, title) => ({ id: `00000000-0000-4000-8000-${String(id).padStart(12, "0")}`, date, category, amount, title, counterparty: "연구소", memo: "", voided: false, revision: 1, updated_by: "admin@example.com", updated_at: "2026-11-04T03:00:00Z" });
rows = [entry(1, "revenue", 1000000, "교사 연수 강의료"), entry(2, "coffee", 18000, "함께 연구하는 커피"), entry(3, "meal", 42000, "연구 모임 점심"), entry(4, "rent", 500000, "연구소 월세"), entry(5, "other_income", 200000, "운영자 입금")];
try {
  // Test-tab-only injection: production files and their auth flow are never altered.
  await page.route("**/js/admin.js", route => route.fulfill({ contentType: "text/javascript", body: `let uid='test-admin';export const adminAccountId=()=>uid;export const requireAdmin=async()=>true;export const adminFetch=(url,options)=>fetch(url,options);export const onAdminAccountChange=listener=>{window.testAccountChange=()=>{uid=null;listener(null)}};` }));
  await page.route("**/api/research-erp**", async route => {
    const request = route.request();
    if (request.method() === "GET") {
      const month = new URL(request.url()).searchParams.get("month");
      return route.fulfill({ status: rejectLoad ? 503 : 200, json: rejectLoad ? { reason: loadReason } : { entries: rows.filter(e => e.date.startsWith(month)), storage: "google_sheets" } });
    }
    const input = request.postDataJSON();
    if (request.method() === "POST") postIds.push(input.id);
    if (rejectSave) return route.fulfill({ status: 503, json: { reason: "temporarily_unavailable" } });
    const old = rows.find(e => e.id === input.id);
    const saved = { ...input, revision: old ? old.revision + 1 : 1, updated_by: "admin@example.com", updated_at: new Date().toISOString() };
    rows = rows.filter(e => e.id !== saved.id); rows.push(saved);
    return route.fulfill({ status: 200, json: { entry: saved } });
  });
  page.setDefaultTimeout(10000);
  await page.goto(`${base}/research-erp.html`, { waitUntil: "domcontentloaded" });
  await page.getByText("선택한 월 전체 기준", { exact: false }).waitFor();
  assert.equal(await page.locator("[data-summary] article").count(), 4);
  assert.match(await page.locator("[data-load-status]").innerText(), /Google 시트 연결됨/);
  assert.match(await page.locator("[data-summary]").innerText(), /440,000원/);
  assert.match(await page.locator("[data-summary]").innerText(), /640,000원/);
  await page.locator("[data-direction]").selectOption("in");
  assert.equal(await page.locator("tbody tr").count(), 2);
  await page.locator("[data-direction]").selectOption("out");
  assert.equal(await page.locator("tbody tr").count(), 3);
  await page.locator("[data-direction]").selectOption("all");
  assert.equal(await page.locator("[data-preset]").count(), 6);
  await page.locator("[data-filter]").selectOption("coffee");
  assert.equal(await page.locator("tbody tr").count(), 1);
  assert.match(await page.locator("[data-summary]").innerText(), /1,000,000원/);
  await page.locator("[data-filter]").selectOption("all");
  await page.locator("[data-search]").fill("월세"); assert.equal(await page.locator("tbody tr").count(), 1);
  await page.locator("[data-search]").fill("");
  await page.screenshot({ path: new URL("research-erp-desktop.png", output).pathname, fullPage: true });
  console.log("Desktop screen verified; checking mobile");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: new URL("research-erp-mobile.png", output).pathname, fullPage: true });
  console.log("Mobile screen verified; checking transactions");
  await page.locator('[data-preset="coffee"]').click();
  await page.locator('[name="amount"]').fill("4,500");
  await page.locator('[name="title"]').fill('<img src=x onerror="alert(1)">');
  rejectSave = true;
  await page.locator("[data-save]").click();
  await page.getByText("저장 결과를 확인하지 못했습니다.", { exact: false }).waitFor();
  assert.equal(await page.locator('[name="amount"]').inputValue(), "4,500");
  rejectSave = false; await page.locator("[data-save]").click();
  await page.getByText("저장했습니다.", { exact: true }).waitFor();
  assert.equal(postIds[0], postIds[1], "Retry keeps the same creation ID");
  assert.equal(await page.locator("tbody img").count(), 0, "Transaction text cannot inject HTML");
  assert.equal(await page.locator('[name="amount"]').inputValue(), "");
  // Create an intentional duplicate only after checking the acknowledgement.
  await page.locator('[data-preset="coffee"]').click();
  await page.locator('[name="amount"]').fill("18000"); await page.locator('[name="title"]').fill("함께 연구하는 커피");
  await page.locator("[data-save]").click(); await page.locator("[data-duplicate]:visible").waitFor();
  const before = rows.length;
  await page.locator("[data-duplicate-confirm]").check();
  assert.equal(await page.locator("[data-duplicate-confirm]").isChecked(), true);
  await page.locator("[data-save]").click(); await page.getByText("저장했습니다.", { exact: true }).waitFor();
  assert.equal(rows.length, before + 1);
  // Cancel, include cancelled, then restore without deleting anything.
  await page.locator('[data-void="00000000-0000-4000-8000-000000000004"]').click();
  await page.waitForFunction(() => !document.querySelector('[data-save]').disabled);
  assert.equal(rows.find(e => e.title === "연구소 월세").voided, true);
  assert.equal(await page.locator('[data-edit="00000000-0000-4000-8000-000000000004"]').count(), 0);
  await page.locator("[data-voided]").check();
  await page.locator('[data-void="00000000-0000-4000-8000-000000000004"]').click();
  await page.waitForFunction(() => !document.querySelector('[data-save]').disabled);
  assert.equal(rows.find(e => e.title === "연구소 월세").voided, false);
  // Optimistic edit UI, then move the transaction to a different month.
  await page.locator('[data-edit="00000000-0000-4000-8000-000000000003"]').click();
  await page.locator('[name="amount"]').fill("43000");
  await page.locator('[name="date"]').fill("2025-01-15");
  await page.locator("[data-save]").click();
  await page.getByText("2025-01월 장부에 저장했습니다.", { exact: false }).waitFor();
  assert.equal(await page.locator('[data-edit="00000000-0000-4000-8000-000000000003"]').count(), 0);
  const downloadPromise = page.waitForEvent("download"); await page.locator("[data-export]").click();
  const download = await downloadPromise; assert.match(download.suggestedFilename(), /BOOONG-연구소/);
  await page.locator("[data-month]").fill("2024-01"); await page.locator("[data-month]").dispatchEvent("change");
  await page.getByText("이달의 첫 거래를 기록해보세요.").waitFor();
  assert.equal(await page.locator('[name="date"]').inputValue(), "2024-01-01");
  await page.screenshot({ path: new URL("research-erp-empty-mobile.png", output).pathname, fullPage: true });
  rejectLoad = true; loadReason = "sheets_not_configured";
  await page.locator("[data-month]").fill("2024-02"); await page.locator("[data-month]").dispatchEvent("change");
  await page.locator("[data-retry]").waitFor();
  assert.equal(await page.locator("[data-save]").isDisabled(), true);
  assert.match(await page.locator("[data-load-status]").innerText(), /Google 시트 연결 설정/);
  assert.equal(await page.locator("[data-summary] article").count(), 0);
  rejectLoad = false; await page.locator("[data-retry]").click();
  await page.waitForFunction(() => !document.querySelector('[data-save]').disabled);
  await page.evaluate(() => window.testAccountChange());
  assert.equal(await page.locator("[data-save]").isDisabled(), true);
  assert.equal(await page.locator("tbody").count(), 0);
  assert.equal(await page.locator('[name="title"]').inputValue(), "");
  assert.deepEqual(errors, []);
  const actualApi = await page.request.get(`${base}/api/research-erp?month=2026-11`);
  assert.equal(actualApi.status(), 401);
  console.log("ERP browser: desktop/mobile, filters, totals, failed save/retry, HTML escaping, duplicate confirmation, cancel/restore, date move, CSV, empty/error/retry and account-change locking passed. Screenshots: output/playwright/research-erp-*.png");
} finally { await browser.close(); }
