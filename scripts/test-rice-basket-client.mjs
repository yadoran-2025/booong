await context.publicFetch('/api/sessions/training');
assert.equal(publicRequest.options.credentials,'omit');
assert.equal(publicRequest.options.cache,'no-store');
assert.equal(new URL(publicRequest.url,'https://booong.vercel.app').searchParams.get('route'),'/api/sessions/training');
const startup = source.slice(source.indexOf('async function start('));
