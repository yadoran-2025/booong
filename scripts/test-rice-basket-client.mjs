const context=vm.createContext({URL,location:{origin:'https://booong.vercel.app'},loadAdminModule:async()=>{adminLoads++;return {adminAccountId:()=>uid,adminFetch:()=>new Promise(resolve=>{release=resolve;}),requireAdmin:async()=>true,onAdminAccountChange:listener=>listener(uid)};}});
vm.runInContext(operator,context);
const url=new URL(context.operatorUrl('/api/surveys/id/results?session=training&revision=3'),'https://booong.vercel.app');
assert.equal(url.pathname,'/api/rice-basket');assert.equal(url.searchParams.get('route'),'/api/surveys/id/results');assert.equal(url.searchParams.get('session'),'training');
assert.throws(()=>context.operatorUrl('https://evil.example/api/admin'));
assert.throws(()=>context.operatorUrl('/admin.html'));
context.fetch=async()=>new Response('{}');
await context.publicFetch('/api/sessions/training');
assert.equal(adminLoads,0,'참가자 공유 화면은 Google 로그인 모듈을 내려받거나 초기화하지 않는다');
