assert.equal(accountEvent,uid);assert.equal(adminLoads,1,'관리 작업은 이미 불러온 인증 모듈을 재사용한다');
let callback,reads=0,checks=0;
const app={replaceChildren(){}};
const source=fs.readFileSync(new URL('../rice-basket/app.js',import.meta.url),'utf8').replace(/^import.*;\n/gm,'');
const boot=vm.createContext({URLSearchParams,location:{search:'?admin=1'},document:{querySelector:()=>app},window:{addEventListener(){}},clearInterval(){},onAdminAccountChange:cb=>{callback=cb;},requireAdmin:async()=>{checks++;return false;},operatorFetch:()=>{reads++;throw new Error('권한 없는 데이터 접근');}});
